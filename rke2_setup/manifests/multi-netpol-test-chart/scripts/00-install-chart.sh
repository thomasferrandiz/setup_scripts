#!/usr/bin/env bash
# Installs the rke2-multus chart under test (a .tar.gz given as the first
# argument or via CHART_TGZ) with the multi-networkpolicy-nftables
# controller enabled, then waits for it to become ready. Corresponds to the
# "Common setup" section, step 1-2, of multi-network-policy-test-plan.md.
#
# The chart replaces the cluster's existing rke2-multus release (keeping
# the values it was installed with); the previous revision is recorded so
# that `90-cleanup.sh --all` can roll back to it.
set -euo pipefail
source "$(dirname "$0")/lib.sh"
require_helm

CHART_TGZ="${1:-${CHART_TGZ:-}}"
if [[ -z "${CHART_TGZ}" || ! -f "${CHART_TGZ}" ]]; then
  echo "usage: $0 /path/to/rke2-multus-<version>.tgz (or set CHART_TGZ)" >&2
  exit 1
fi
CHART_TGZ="$(cd "$(dirname "${CHART_TGZ}")" && pwd)/$(basename "${CHART_TGZ}")"

log "Chart under test: ${CHART_TGZ}"
helm show chart "${CHART_TGZ}" | grep -E '^(name|version|appVersion):'
if ! helm show values "${CHART_TGZ}" | grep -q '^multiNetworkPolicy:'; then
  echo "ERROR: ${CHART_TGZ} has no multiNetworkPolicy values; not a chart with the nftables controller" >&2
  exit 1
fi

if [[ -f "${CHART_STATE_ENV}" ]]; then
  # Re-run: keep the original rollback target and CRD ownership.
  load_chart_state
  info "existing ${CHART_STATE_ENV} found, keeping PREV_REVISION='${PREV_REVISION}' CRD_APPLIED=${CRD_APPLIED}"
else
  PREV_REVISION="$(helm status "${HELM_RELEASE}" -n "${HELM_NAMESPACE}" -o json 2>/dev/null | jq -r '.version // empty' || true)"
  CRD_APPLIED=0
fi

# Helm only installs crds/ on first install, never on upgrade, and on RKE2
# the CRDs normally come from the separate rke2-multus-crd chart.
log "Ensuring the MultiNetworkPolicy CRD exists"
if kubectl get crd multi-networkpolicies.k8s.cni.cncf.io >/dev/null 2>&1; then
  info "CRD already present"
else
  crd_path="$(tar -tzf "${CHART_TGZ}" | grep -E '/crds/multi-networkpolicies\.k8s\.cni\.cncf\.io\.yaml$' | head -n1 || true)"
  if [[ -z "${crd_path}" ]]; then
    echo "ERROR: CRD not installed and not found in ${CHART_TGZ}; install the matching rke2-multus-crd chart first" >&2
    exit 1
  fi
  info "applying ${crd_path} from the chart tarball"
  tar -xzOf "${CHART_TGZ}" "${crd_path}" | kubectl apply -f -
  kubectl wait --for=condition=Established crd/multi-networkpolicies.k8s.cni.cncf.io --timeout=60s
  CRD_APPLIED=1
fi

cat > "${CHART_STATE_ENV}" <<STATE
# Generated by 00-install-chart.sh - do not edit by hand.
CHART_TGZ='${CHART_TGZ}'
PREV_REVISION='${PREV_REVISION}'
CRD_APPLIED=${CRD_APPLIED}
STATE

if kubectl get helmcharts.helm.cattle.io -n "${HELM_NAMESPACE}" "${HELM_RELEASE}" >/dev/null 2>&1; then
  info "NOTE: HelmChart ${HELM_NAMESPACE}/${HELM_RELEASE} is managed by RKE2; an RKE2 restart or a change"
  info "      to that HelmChart/HelmChartConfig will redeploy the packaged chart over the one under test."
fi

log "helm upgrade --install ${HELM_RELEASE} (previous revision: ${PREV_REVISION:-none})"
helm_upgrade_chart "${CHART_TGZ}"

log "Waiting for the multus (thick) and controller DaemonSet rollouts"
if ! multus_is_thick; then
  echo "ERROR: the release does not run the multus thick plugin; keep thickPlugin.enabled=true in ${CHART_VALUES}" >&2
  exit 1
fi
wait_multus_rollout
wait_controller_rollout

log "Verifying CRD discovery"
kubectl get crd multi-networkpolicies.k8s.cni.cncf.io
kubectl api-resources --api-group=k8s.cni.cncf.io

log "Controller pods"
kubectl get pods -n "${CONTROLLER_NAMESPACE}" -l "${CONTROLLER_LABEL_SELECTOR}" -o wide
kubectl get daemonset -n "${CONTROLLER_NAMESPACE}" "${CONTROLLER_DAEMONSET}" \
  -o jsonpath='{range .spec.template.spec.containers[*]}{"    image: "}{.image}{"\n"}{"    args:  "}{.args}{"\n"}{end}'

echo
echo "Chart installed and controller ready."
